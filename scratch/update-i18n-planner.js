// For each language, find where `"btn_sos":` is inside that language dictionary,
// and append the formatted keys right after it.
let updatedContent = content;

for (const [lang, keys] of Object.entries(keysPerLang)) {
  // Find "lang": { ... "btn_sos": "..."
  const langHeader = `"${lang}": {`;
  const langIdx = updatedContent.indexOf(langHeader);
  if (langIdx === -1) {
    console.error(`Language ${lang} not found in content!`);
    continue;
  }

  // Find the next dictionary start or end of DICTIONARIES
  const nextLangIdx = updatedContent.indexOf("\n  },", langIdx);
  if (nextLangIdx === -1) {
    console.error(`Closing brace for ${lang} not found!`);
    continue;
  }

  // Generate code lines for new keys
  const lines = [];
  for (const [k, v] of Object.entries(keys)) {
    // Escape quotes in v
    const escapedV = v.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
    lines.push(`    "${k}": "${escapedV}",`);
  }
  const insertion = "\n" + lines.join("\n");

  // Insert right before nextLangIdx
  updatedContent = updatedContent.slice(0, nextLangIdx) + insertion + updatedContent.slice(nextLangIdx);
  console.log(`Updated ${lang} with ${Object.keys(keys).length} Trip Planner keys.`);
}

fs.writeFileSync(i18nPath, updatedContent, "utf8");
